export type TranslationKey = keyof typeof DICTIONARY;

export function tr(key: TranslationKey, lang?: LanguageCode): string {
  const effective = lang || detectDefaultLanguage();
  return DICTIONARY[key][effective] || DICTIONARY[key].en;
}

export function getReasonLabel(reason: LessReasonKey, lang?: LanguageCode): string {
  const map: Record<LessReasonKey, TranslationKey> = {
    phone: 'phone',
    tired: 'tired',
    away: 'away',
    sick: 'sick',
    distracted: 'distracted',
  };
  return tr(map[reason], lang);
}

export function formatNum(n: number, lang?: LanguageCode): string {
  return Number(n).toLocaleString(getLocale(lang));
}

export function formatDuration(minutes: number, lang?: LanguageCode): string {
  const m = Math.round(minutes);
  const h = Math.floor(m / 60);
  const r = m % 60;
  if (h > 0) {
    return `${formatNum(h, lang)} ${tr('hr', lang)}${r > 0 ? ` ${formatNum(r, lang)} ${tr('min', lang)}` : ''}`;
  }
  return `${formatNum(r, lang)} ${tr('min', lang)}`;
}

export function calcPct(actual: number, planned: number): number {
  return planned > 0 ? Math.round(((actual - planned) / planned) * 100) : 0;
}

export function formatPctDelta(value: number, lang?: LanguageCode): string {
  const prefix = value > 0 ? '+' : value < 0 ? '−' : '';
  return `${prefix}${formatNum(Math.abs(value), lang)}%`;
}
