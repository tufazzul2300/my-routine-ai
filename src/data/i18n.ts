export const LOCALES: Record<LanguageCode, string> = {
  bn: 'bn-BD',
  en: 'en-US',
  hi: 'hi-IN',
  ar: 'ar-EG',
  es: 'es-ES',
};

export function detectDefaultLanguage(): LanguageCode {
  if (typeof navigator === 'undefined') return 'en';
  const code = String(navigator.language || 'en').slice(0, 2).toLowerCase() as LanguageCode;
  return LANGUAGES[code] ? code : 'en';
}

export function getLocale(lang?: LanguageCode): string {
  const effective = lang || detectDefaultLanguage();
  return LOCALES[effective] || 'en-US';
}

